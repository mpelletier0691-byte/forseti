/**
 * Tiny DSL over PdfDocument that lays out caption blocks, paragraph stubs,
 * handwriting lines, signature blocks, and a footer.
 *
 * Keeps a running cursor (left, top) and starts a new page when content would
 * overflow the bottom margin.
 */
class DraftDsl(
    private val pdf: PdfDocument,
    val doc: DraftDoc,
    val prefill: DraftPrefill
) {
    private var pageNumber = 0
    private var page: PdfDocument.Page? = null
    private var canvas: Canvas? = null
    private var cursorY: Float = 0f

    private val pageWidth = 612
    private val pageHeight = 792
    private val marginX = 54f
    private val marginTop = 54f
    private val marginBottom = 54f

    private val titlePaint = TextPaint().apply {
        isAntiAlias = true
        color = Color.BLACK
        textSize = 14f
        typeface = Typeface.create(Typeface.SERIF, Typeface.BOLD)
    }
    private val bodyPaint = TextPaint().apply {
        isAntiAlias = true
        color = Color.BLACK
        textSize = 11f
        typeface = Typeface.SERIF
    }
    private val labelPaint = TextPaint().apply {
        isAntiAlias = true
        color = Color.DKGRAY
        textSize = 9.5f
        typeface = Typeface.create(Typeface.SERIF, Typeface.ITALIC)
    }
    private val linePaint = Paint().apply {
        color = Color.LTGRAY
        strokeWidth = 0.6f
        style = Paint.Style.STROKE
        isAntiAlias = true
    }

    fun run(template: DraftDsl.() -> Unit) {
        // If template() throws, we must still finishPage() — otherwise
        // PdfDocument.writeTo() throws IllegalStateException ("Current page not closed")
        // and the app crashes while "Building PDF…" is showing.
        try {
            startPage()
            template()
        } finally {
            finishPage()
        }
    }

    private fun startPage() {
        pageNumber++
        val info = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
        page = pdf.startPage(info)
        canvas = page!!.canvas
        cursorY = marginTop
        if (pageNumber > 1) drawHeader("(continued)")
    }

    private fun finishPage() {
        page?.let { pdf.finishPage(it) }
        page = null
        canvas = null
    }

    private fun newPage() {
        finishPage()
        startPage()
    }

    private fun ensureSpace(needed: Float) {
        if (cursorY + needed > pageHeight - marginBottom) newPage()
    }

    private fun drawHeader(label: String) {
        val c = canvas ?: return
        c.drawText(label, marginX, marginTop - 12f, labelPaint)
    }

    fun caption() {
        val width = pageWidth - 2 * marginX
        canvas?.drawText("UNITED STATES DISTRICT COURT", marginX, cursorY + 12f, titlePaint)
        cursorY += 16f
        labeledLine("DISTRICT OF", prefill.court)
        cursorY += 4f
        canvas?.drawLine(marginX, cursorY, marginX + width, cursorY, linePaint)
        cursorY += 14f
        labeledLine("Plaintiff(s)", prefill.plaintiff)
        canvas?.drawText("v.", marginX, cursorY + 12f, bodyPaint)
        cursorY += 16f
        labeledLine("Defendant(s)", prefill.defendant)
        cursorY += 4f
        canvas?.drawLine(marginX, cursorY, marginX + width, cursorY, linePaint)
        cursorY += 14f
        labeledLine("Case No.", prefill.caseNumber)
        cursorY += 8f
        canvas?.drawText("Re: ${doc.title}  (${doc.ruleCitation})", marginX, cursorY + 10f, labelPaint)
        cursorY += 16f
        canvas?.drawLine(marginX, cursorY, marginX + width, cursorY, linePaint)
        cursorY += 12f
    }

    private fun labeledLine(label: String, value: String?) {
        ensureSpace(20f)
        val c = canvas ?: return
        c.drawText("$label: ", marginX, cursorY + 12f, bodyPaint)
        val labelWidth = bodyPaint.measureText("$label: ")
        val xLine = marginX + labelWidth
        val xEnd = pageWidth - marginX
        c.drawLine(xLine, cursorY + 14f, xEnd, cursorY + 14f, linePaint)
        if (!value.isNullOrBlank()) {
            c.drawText(value, xLine + 2f, cursorY + 12f, bodyPaint)
        }
        cursorY += 22f
    }

    fun sectionTitle(title: String) {
        ensureSpace(28f)
        cursorY += 8f
        canvas?.drawText(title, marginX, cursorY + 12f, titlePaint)
        cursorY += 18f
    }

    fun preamble(text: String) {
        paragraph(text)
        cursorY += 4f
    }

    fun paragraph(text: String) {
        if (text.isBlank()) return
        if (canvas == null) return
        val width = (pageWidth - 2 * marginX).toInt()
        val layout = StaticLayout.Builder.obtain(text, 0, text.length, bodyPaint, width)
            .setAlignment(Layout.Alignment.ALIGN_NORMAL)
            .setLineSpacing(2f, 1.0f)
            .build()
        ensureSpace(layout.height.toFloat() + 6f)
        val c = canvas ?: return
        c.save()
        c.translate(marginX, cursorY)
        layout.draw(c)
        c.restore()
        cursorY += layout.height + 6f
    }

    fun labeledBlank(label: String) {
        paragraph(label)
        handwritingLines(count = 1)
    }

    fun handwritingLines(count: Int) {
        val xStart = marginX
        val xEnd = pageWidth - marginX
        repeat(count) {
            ensureSpace(22f)
            cursorY += 16f
            canvas?.drawLine(xStart, cursorY, xEnd, cursorY, linePaint)
            cursorY += 4f
        }
        cursorY += 6f
    }

    fun numberedBlanks(count: Int, label: String) {
        val xEnd = pageWidth - marginX
        for (i in 1..count) {
            ensureSpace(40f)
            val prefix = "$i. "
            canvas?.drawText("$prefix$label:", marginX, cursorY + 12f, labelPaint)
            cursorY += 18f
            canvas?.drawLine(marginX, cursorY, xEnd, cursorY, linePaint)
            cursorY += 18f
            canvas?.drawLine(marginX, cursorY, xEnd, cursorY, linePaint)
            cursorY += 8f
        }
    }

    fun prayer(text: String) {
        cursorY += 6f
        paragraph(text)
    }

    fun signatureBlock() {
        ensureSpace(120f)
        cursorY += 14f
        canvas?.drawText("Respectfully submitted,", marginX, cursorY + 12f, bodyPaint)
        cursorY += 36f
        canvas?.drawLine(marginX, cursorY, marginX + 240f, cursorY, linePaint)
        canvas?.drawText("Signature", marginX, cursorY + 11f, labelPaint)
        cursorY += 20f
        labeledLine("Printed name", prefill.signerName)
        labeledLine("Address", prefill.signerAddress)
        labeledLine("Phone", prefill.signerPhone)
        labeledLine("Email", prefill.signerEmail)
        labeledLine("Date", null)
    }

    fun certificateOfService() {
        sectionTitle("CERTIFICATE OF SERVICE")
        paragraph("I certify that on the date below I served a true copy of the foregoing on all parties of record by the means indicated.")
        handwritingLines(count = 3)
        labeledLine("Date", null)
    }

    fun footer(text: String) {
        if (text.isBlank()) return
        val width = (pageWidth - 2 * marginX).toInt()
        val layout = StaticLayout.Builder.obtain(text, 0, text.length, labelPaint, width)
            .setAlignment(Layout.Alignment.ALIGN_NORMAL)
            .build()
        ensureSpace(layout.height.toFloat() + 8f)
        val c = canvas ?: return
        c.save()
        c.translate(marginX, (pageHeight - marginBottom + 8f))
        layout.draw(c)
        c.restore()
    }

    fun blankFor(value: String?, placeholder: String): String =
        value?.takeIf { it.isNotBlank() } ?: "[$placeholder]"
}
