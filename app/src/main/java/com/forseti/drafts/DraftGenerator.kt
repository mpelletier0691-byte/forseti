/**
 * Builds printable PDFs for FRCP-required filings that have no official Pro Se form.
 *
 * Each template uses the shared layout primitives in [DraftDsl]: a standard caption
 * block, numbered paragraph stubs with wide handwriting lines, signature block,
 * and a footer citing the rule the form satisfies.
 *
 * Output is always letter-size (612 x 792 pt) so it prints cleanly to US Letter.
 */
@Singleton
class DraftGenerator @Inject constructor(
    @ApplicationContext private val context: Context
) {
    fun generate(doc: DraftDoc, prefill: DraftPrefill = DraftPrefill()): File {
        require(doc.source is DraftSource.Generated) {
            "DraftGenerator only handles Generated docs; ${doc.id} is ${doc.source}"
        }
        val template = Templates[doc.source.templateId]
            ?: error("No template registered for ${doc.source.templateId}")
        val pdf = PdfDocument()
        val out = File(context.cacheDir, "draft_${doc.id}.pdf")
        try {
            DraftDsl(pdf, doc, prefill).run(template)
            FileOutputStream(out).use { stream -> pdf.writeTo(stream) }
        } finally {
            runCatching { pdf.close() }
        }
        return out
    }
}

